import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { spawn } from 'node:child_process';
import path from 'node:path';
import { chromium } from 'playwright';

const root = process.cwd();
const pages = JSON.parse(await readFile('src/content/pages.json', 'utf8'));
const externalUrl = process.env.SHOWCASE_URL;
const base = externalUrl || 'http://127.0.0.1:4173/';
const server = externalUrl ? null : spawn(process.execPath, [path.join(root, 'node_modules/vite/bin/vite.js'), 'preview', '--host', '127.0.0.1', '--port', '4173', '--strictPort'], { cwd: root, stdio: 'pipe', windowsHide: true });
const results = [], errors = [];
let browser;
try {
  for (let i = 0; i < 60; i++) {
    try { if ((await fetch(base)).ok) break; } catch {}
    await new Promise(resolve => setTimeout(resolve, 150));
  }
  browser = await chromium.launch({ channel: process.env.BROWSER_CHANNEL || (process.platform === 'win32' ? 'msedge' : undefined), headless: true });
  await mkdir('.qa/screens', { recursive: true });
  for (const viewport of [{ width: 1366, height: 768 }, { width: 1920, height: 1080 }, { width: 1707, height: 782 }, { width: 1024, height: 768 }, { width: 390, height: 844 }]) {
    const page = await browser.newPage({ viewport, deviceScaleFactor: 1, reducedMotion: 'reduce' });
    page.on('pageerror', error => errors.push(error.message));
    page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
    await page.goto(base);
    await page.locator('.canvas').waitFor();
    for (const step of pages) {
      await page.evaluate(id => { location.hash = `#/step/${String(id).padStart(2, '0')}`; }, step.id);
      await page.waitForFunction(title => document.querySelector('h1')?.textContent === title, step.title);
      await page.locator('.canvas').waitFor();
      await page.evaluate(() => document.fonts.ready);
      assert.equal(await page.locator('h1').textContent(), step.title);
      const measurements = await page.evaluate(() => ({ width: document.documentElement.scrollWidth, mainWidth: document.querySelector('main').scrollWidth, mainClient: document.querySelector('main').clientWidth, mainHeight: document.querySelector('main').scrollHeight, mainClientHeight: document.querySelector('main').clientHeight, tableOverflow: [...document.querySelectorAll('.table-scroll')].filter(element => element.scrollWidth > element.clientWidth + 1).length, viewport: innerWidth, text: document.querySelector('.canvas').textContent.trim().length }));
      assert.ok(measurements.width <= viewport.width, `Step ${step.id} overflows at ${viewport.width}: ${measurements.width}`);
      assert.ok(measurements.mainWidth <= measurements.mainClient, `Step ${step.id} main content overflows at ${viewport.width}`);
      if (viewport.width >= 1366) {
        assert.ok(measurements.mainHeight <= measurements.mainClientHeight + 1, `Step ${step.id} needs vertical scrolling at ${viewport.width}: ${measurements.mainHeight - measurements.mainClientHeight}px`);
        assert.equal(measurements.tableOverflow, 0, `Step ${step.id} needs horizontal table scrolling at ${viewport.width}`);
      }
      assert.ok(measurements.text > 25, `Step ${step.id} has no content`);
      assert.equal(await page.getByRole('button', { name: '查看来源' }).count(), 0);
      assert.doesNotMatch(await page.locator('.canvas').innerText(), /保留原表|本次保留|样例直接读取|未配齐|未保存|不代表|不填入|不生成|SHA-256|模型字段/);
      await page.locator('.canvas img').evaluateAll(images => Promise.all(images.map(i => i.decode())));
      await page.screenshot({ path: `.qa/screens/${viewport.width}-${String(step.id).padStart(2, '0')}.png`, fullPage: true });
      results.push({ step: step.id, viewport: viewport.width, width: measurements.width });
    }
    await page.close();
    console.log(`[PASS] 61 pages at ${viewport.width} × ${viewport.height}`);
  }
  const page = await browser.newPage({ viewport: { width: 1366, height: 768 }, reducedMotion: 'reduce' });
  page.on('pageerror', error => errors.push(error.message));
  const go = async id => { await page.goto(`${base}#/step/${String(id).padStart(2, '0')}`); await page.locator('.canvas').waitFor(); };
  await go(13);
  assert.equal(await page.locator('#duplicate-time option').count(), 4);
  const firstPair = await page.locator('tbody').innerText();
  await page.locator('#duplicate-time').selectOption({ index: 3 });
  assert.notEqual(await page.locator('tbody').innerText(), firstPair);
  assert.equal(await page.locator('tbody tr').count(), 2);
  assert.equal(await page.locator('.empty-value').count(), 0);
  await go(25);
  await page.locator('.controls select').selectOption('2');
  assert.equal(await page.locator('tbody tr').count(), 5);
  const firstGroup = await page.locator('tbody').innerText();
  await page.getByRole('button', { name: '下一组记录' }).click();
  assert.notEqual(await page.locator('tbody').innerText(), firstGroup);
  await page.getByRole('button', { name: '下一组记录' }).click();
  assert.equal(await page.locator('tbody tr').count(), 3);
  assert.equal(await page.getByRole('button', { name: '下一组记录' }).isDisabled(), true);
  await page.locator('.controls select').selectOption('0');
  assert.equal(await page.locator('tbody tr').count(), 2);
  assert.equal(await page.locator('.table-pagination').count(), 0);
  await go(21);
  await page.locator('#changed-field').selectOption('weather_ws_hub');
  assert.match(await page.locator('.table-pagination').innerText(), /1–5 \/ 58 条/);
  assert.equal(await page.locator('main').evaluate(element => element.scrollHeight <= element.clientHeight + 1), true, 'Wind-speed change records must fit the desktop page');
  for (let group = 1; group < 12; group++) await page.getByRole('button', { name: '下一组记录' }).click();
  assert.equal(await page.locator('tbody tr').count(), 3);
  assert.equal(await page.getByRole('button', { name: '下一组记录' }).isDisabled(), true);
  await go(22);
  await page.locator('.feature-groups section').nth(2).getByRole('button').nth(3).click();
  const selected = await page.locator('.feature-selected code').textContent();
  await page.getByRole('button', { name: '下一页' }).click();
  await page.getByRole('button', { name: '上一页' }).click();
  assert.equal(await page.locator('.feature-selected code').textContent(), selected);
  await page.getByRole('button', { name: '全部页面' }).click();
  await page.screenshot({ path: '.qa/screens/state-contents.png' });
  assert.equal(await page.locator('#contents li a').count(), 61);
  await page.locator('#contents a[href="#/step/57"]').click();
  await page.waitForFunction(() => location.hash === '#/step/57');
  assert.equal(await page.locator('#contents').count(), 0);
  const before = page.url();
  await page.locator('.range-control input').focus();
  const initial = await page.locator('.range-control input').inputValue();
  await page.keyboard.press('ArrowRight');
  assert.notEqual(await page.locator('.range-control input').inputValue(), initial);
  assert.equal(page.url(), before, 'Range arrow must not navigate');
  await page.locator('h1').focus();
  await page.keyboard.press('ArrowLeft');
  await page.waitForFunction(() => location.hash === '#/step/56');
  await page.goBack();
  await page.waitForFunction(() => location.hash === '#/step/57');
  await page.reload(); await page.locator('.canvas').waitFor();
  assert.equal(await page.locator('h1').textContent(), pages[56].title);
  await page.locator('.skip-link').focus();
  await page.keyboard.press('Enter');
  assert.equal(new URL(page.url()).hash, '#/step/57');
  assert.equal(await page.locator('h1').evaluate(e => e === document.activeElement), true);
  await page.keyboard.press('End');
  await page.waitForFunction(() => location.hash === '#/step/61');
  assert.equal(await page.getByRole('button', { name: '下一页' }).isDisabled(), true);
  await page.getByRole('searchbox').fill('不存在的来源');
  assert.equal(await page.getByRole('status').textContent(), '没有匹配材料。请更换关键词。');
  await page.screenshot({ path: '.qa/screens/state-empty.png' });
  await page.getByRole('searchbox').fill('检查点');
  assert.equal(await page.locator('.source-inventory details').count(), 1);
  await page.getByRole('searchbox').clear();
  assert.equal(await page.getByRole('button', { name: '查看来源' }).count(), 0);
  await page.locator('.source-inventory details').first().locator('summary').click();
  assert.doesNotMatch(await page.locator('.source-inventory').innerText(), /SHA-256|sha256|防御|未配齐|未保存/);
  assert.ok(await page.locator('.source-page-links a').count() > 0);
  await page.screenshot({ path: '.qa/screens/state-source.png' });
  await page.locator('h1').focus();
  await page.keyboard.press('Home');
  await page.waitForFunction(() => location.hash === '#/step/01');
  await page.waitForFunction(title => document.querySelector('h1')?.textContent === title, pages[0].title);
  assert.equal(await page.getByRole('button', { name: '上一页' }).isDisabled(), true);
  await go(52);
  const previousCoverage = await page.locator('.controls output').textContent();
  await page.locator('.controls input').fill('0');
  assert.notEqual(await page.locator('.controls output').textContent(), previousCoverage);
  await go(58);
  await page.getByRole('button', { name: 'FP 误报' }).click();
  assert.match(await page.locator('.confusion-definition').textContent(), /真实正常/);
  await go(43);
  for (let i = 0; i < 3; i++) {
    await page.getByRole('button', { name: '报告原图' }).nth(i).click();
    await page.locator('.report-figure img').evaluate(img => img.decode());
    await page.locator('.report-figure').scrollIntoViewIfNeeded();
    await page.screenshot({ path: `.qa/screens/state-model-${i + 1}.png` });
    assert.equal(await page.locator('.report-figure img').evaluate(img => img.complete && img.naturalWidth > 0), true);
    assert.equal(await page.locator('main').evaluate(element => element.scrollHeight <= element.clientHeight + 1), true, 'Expanded model figure must fit the desktop page');
    assert.equal(await page.getByRole('link', { name: '查看大图' }).count(), 1);
    await page.getByRole('button', { name: '收起原图' }).click();
  }
  await go(48);
  await page.getByRole('button', { name: '训练原图' }).click();
  await page.locator('.report-figure img').evaluate(img => img.decode());
  assert.equal(await page.locator('main').evaluate(element => element.scrollHeight <= element.clientHeight + 1), true, 'Saved training figure must fit the desktop page');
  await page.close();
  const tableKeyboard = await browser.newPage({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' });
  await tableKeyboard.goto(`${base}#/step/60`);
  await tableKeyboard.locator('.canvas').waitFor();
  const reportTable = tableKeyboard.getByRole('region', { name: '三模型报告指标' });
  await reportTable.focus();
  await tableKeyboard.keyboard.press('ArrowRight');
  await tableKeyboard.waitForFunction(() => document.querySelector('.table-scroll').scrollLeft > 0);
  const rightPosition = await reportTable.evaluate(element => element.scrollLeft);
  assert.equal(new URL(tableKeyboard.url()).hash, '#/step/60');
  await tableKeyboard.screenshot({ path: '.qa/screens/state-table-scroll.png' });
  await tableKeyboard.keyboard.press('ArrowLeft');
  await tableKeyboard.waitForFunction(position => document.querySelector('.table-scroll').scrollLeft < position, rightPosition);
  assert.equal(new URL(tableKeyboard.url()).hash, '#/step/60');
  await tableKeyboard.locator('h1').focus();
  await tableKeyboard.keyboard.press('ArrowLeft');
  await tableKeyboard.waitForFunction(() => document.querySelector('h1')?.textContent === '解释评价指标');
  assert.equal(new URL(tableKeyboard.url()).hash, '#/step/59');
  await tableKeyboard.close();
  const recovery = await browser.newPage();
  let fail = true;
  await recovery.route('**/data/research.json', route => fail ? route.fulfill({ status: 503, body: 'unavailable' }) : route.continue());
  await recovery.goto(base);
  await recovery.getByRole('alert').waitFor();
  await recovery.screenshot({ path: '.qa/screens/state-error.png' });
  fail = false;
  await recovery.getByRole('button', { name: '重新载入' }).click();
  await recovery.locator('.canvas').waitFor();
  await recovery.close();
  assert.deepEqual(errors, []);
  await writeFile('.qa/browser-report.json', JSON.stringify({ passed: results.length, viewports: 5, interactions: 'navigation, history, reload, inputs, duplicate pairs, complete change-record pagination, sources, error recovery, expanded figures, focused table keyboard scrolling', errors, results }, null, 2));
  console.log('[PASS] Navigation, selection persistence, source traceability, keyboard, history, native controls, saved images, load recovery and focused table scrolling');
} finally {
  await browser?.close();
  server?.kill();
}
